"""Prometheus observability metrics for PrivateDocs-LLM."""

from __future__ import annotations

from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest

# Total ask requests labeled by response status
ASK_REQUESTS_TOTAL = Counter(
    "ask_requests_total",
    "Total document question answering requests",
    ["status"],
)

# End-to-end request latency
ASK_LATENCY_SECONDS = Histogram(
    "ask_latency_seconds",
    "End-to-end latency for /v1/ask requests in seconds",
    buckets=[0.05, 0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 30.0, 60.0],
)

# Document retrieval latency (dense + bm25 + rrf)
RETRIEVAL_LATENCY_SECONDS = Histogram(
    "retrieval_latency_seconds",
    "Latency of document retrieval and fusion stage in seconds",
    buckets=[0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.0],
)

# LLM Time-to-First-Token (TTFT)
LLM_TTFT_SECONDS = Histogram(
    "llm_ttft_seconds",
    "Time to first token generation from the LLM server in seconds",
    buckets=[0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0],
)

# Generated tokens counter
LLM_TOKENS_GENERATED_TOTAL = Counter(
    "llm_tokens_generated_total",
    "Total completion tokens generated by the LLM server",
)

# Prompt tokens counter
LLM_TOKENS_PROMPT_TOTAL = Counter(
    "llm_tokens_prompt_total",
    "Total prompt/context tokens sent to the LLM server",
)

# Rate limited requests counter
RATE_LIMITED_TOTAL = Counter(
    "rate_limited_total",
    "Total requests rejected due to rate limiting",
)


def get_prometheus_metrics() -> tuple[bytes, str]:
    """Generate Prometheus exposition text and content-type."""
    return generate_latest(), CONTENT_TYPE_LATEST
